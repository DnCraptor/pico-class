#!/usr/bin/env python3
# mkgfx.py - the sprites of the Watara Supervision examples, drawn as text
# pictures, turned into data for the Supervision screen: sprite_gfx.h,
# catch_gfx.h.
#
# The pictures are the same as for PC Engine, Mega Drive, Game Boy and Lynx
# (tools/pce, tools/md, tools/gb, tools/lynx); each character is a pen
# number ('.' = 0, background). The Supervision has no sprite hardware and
# only 4 shades: every pen is given a shade 0..3 (0 = background, the
# lightest; 3 = the darkest), and the program copies the picture into the
# screen memory itself.
#
# Screen memory: 48 bytes a line, 4 pixels a byte, 2 bits a pixel, the
# left pixel in the lowest two bits. A sprite at x lands at byte x / 4,
# shifted by x % 4 pixels, so every sprite is stored four times, already
# shifted by 0..3 pixels: (w/4 + 1) bytes a line, h lines each.

def shades(rows, pens, scale=1):
    out = []
    for r in rows:
        line = [pens.get(ch, 0) for ch in r]
        line = [v for v in line for _ in range(scale)]
        out += [line] * scale
    return out

def shifted(pix):
    h, w = len(pix), len(pix[0])
    wb = w // 4 + 1
    data = []
    for s in range(4):
        for line in pix:
            row = [0] * (s) + line + [0] * (wb * 4 - w - s)
            for b in range(wb):
                v = 0
                for i in range(4):
                    v |= row[b * 4 + i] << (2 * i)
                data.append(v)
    return data, wb, h

def array(name, data):
    lines = ['\t' + ', '.join('0x%02X' % b for b in data[i:i+12]) for i in range(0, len(data), 12)]
    return 'static const unsigned char %s[%d] = {\n' % (name, len(data)) + ',\n'.join(lines) + '\n};\n'

