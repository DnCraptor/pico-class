ROBOT  = {'1': 3, '2': 3, '3': 1, '4': 3, '5': 2, '6': 2}
ROBOT2 = {'1': 2, '2': 1, '3': 2, '4': 3, '5': 3, '6': 3}   # button A: other shades
BALL   = {'7': 2, '8': 1}
STAR   = {'8': 3, '9': 1}
BASKET = {'A': 3, 'B': 1}

def write(fn, items):
    with open(fn, 'w', newline='\n') as f:
        f.write('/* %s - generated by mkgfx.py, do not edit */\n\n' % fn)
        for name, rows, pens, scale in items:
            data, wb, h = shifted(shades(rows, pens, scale))
            f.write('/* %d bytes x %d lines, shifted by 0..3 pixels */\n' % (wb, h))
            f.write(array(name, data) + '\n')

