shades = {
    'robot':  {'1': 2, '2': 3, '3': 1, '4': 3, '5': 2, '6': 2},
    'ball':   {'7': 2, '8': 1},
    'star':   {'8': 3, '9': 1},
    'basket': {'A': 3, 'B': 2},
}

def write(fn, names):
    with open(fn, 'w', newline='\n') as f:
        f.write('/* %s - generated by mksprites.py, do not edit */\n\n' % fn)
        for n in names:
            f.write(sprite(n, globals()[n], shades[n]) + '\n')

