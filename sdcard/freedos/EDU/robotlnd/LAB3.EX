          Систрица Аленушка            
          и братиц Иванушка            
  Жили-были старик, да старуха, у  них 
была дочка Аленушка да сынок Иванушка. 
  Старик со старухой умирли.  Осталысь 
Аленушка да Иванушка одни-одинешенки.  
  Пошла Аленушка на работу и братика с 
собой взяла. Идуть они по дальнему пу■ 
ти, по  широкому  полю,  и  захателось 
Иванушки пить.                         
  - Сестрица Аленушка, я пить хачу!    
  - Падажди нимношко, братец,  дойдем  
до колодца.                            
  Шли-шли - солнце высок, колодеч  да■ 
леко,  жар  донимает,  пот  виступает. 
  Стоит коровье копытце полно вадицы.  
  - Сестрица Аленушка, хлибну я из ко■ 
пыца!                                  
  - Не пей, брат, теленком станешь!    
                                       
