/* Истина и ложь в Си: отдельного типа нет, это числа */
#include <stdio.h>

int main(void)
{
  printf("5 > 3 : %d\n", 5 > 3);   /* сравнение дает 1 */
  printf("5 < 3 : %d\n", 5 < 3);   /* или 0 */
  /* но истиной считается ЛЮБОЕ число, кроме нуля */
  if (7)  printf("7 - истина\n");
  if (-1) printf("-1 - истина\n");
  if (0)  printf("0 - истина\n"); else printf("0 - ложь\n");
  return 0;
}
