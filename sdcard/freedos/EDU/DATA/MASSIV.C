/* Массив: что будет, если выйти за его границу? */
#include <stdio.h>

/* обе переменные общие (глобальные) и лежат в памяти одна за другой */
int a[5] = { 0 };      /* элементы a[0] .. a[4] */
int b = 77;

int main(void)
{
  int i;
  for (i = 0; i <= 5; i++)
  {
    a[i] = (i + 1) * 10;   /* при i = 5 элемента a[5] нет! */
    printf("a[%d] = %d   b = %d\n", i, a[i], b);
  }
  return 0;
}
